def services_for_prompt() -> str:
    """Форматує каталог послуг для вставки у промпт Claude."""
    lines = []
    for s in STUD_POINT_SERVICES:
        lines.append(f"### {s['name']} (id: {s['id']})")
        lines.append(f"URL: {s['url']}")
        lines.append(f"Категорія: {s['category']}")
        lines.append(f"Опис: {s['summary']}")
        lines.append(f"Які проблеми вирішує: {'; '.join(s['solves'])}")
        lines.append(f"Можливі КПІ (індикативні, без гарантій): {'; '.join(s['potential_kpi'])}")
        lines.append(f"Ціна: {s['price_hint']}")
        lines.append("")
    return "\n".join(lines)


def get_service_by_id(service_id: str):
    for s in STUD_POINT_SERVICES:
        if s["id"] == service_id:
            return s
    return None
